import numpy as np

# 1. Задаем наши линейки (оси)
# Представь, что X — это номера домов на улице, а Y — номера этажей
X = np.array([10, 20, 30])
Y = np.array([1, 2])

print("--- НАШИ ИСХОДНЫЕ ЛИНЕЙКИ ---")
print("Ось X:", X)
print("Ось Y:", Y)
print("\n")

# 2. Магия meshgrid: размножаем линейки в целые таблицы
X_grid, Y_grid = np.meshgrid(X, Y)

print("--- ТАБЛИЦА X (размножили X по вертикали) ---")
print(X_grid)
print("\n")

print("--- ТАБЛИЦА Y (размножили Y по горизонтали) ---")
print(Y_grid)
print("\n")

# 3. Главный фокус: считаем что-то для ВСЕХ точек сразу без циклов!
# Например, сложим координаты X и Y для каждой точки
Z = X_grid + Y_grid

print("--- РЕЗУЛЬТАТ (X + Y для каждой точки) ---")
print(Z)
# Точка (10, 1) станет 11, точка (20, 2) станет 22 и так далее.
